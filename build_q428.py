def js_pair(k, v):
    return json.dumps(k, ensure_ascii=False) + ': ' + json.dumps(v, ensure_ascii=False)

def insert_value_map(name, keys, values):
    """HOURS_ZH / PRICE_ZH / VENUE_ZH: entries at column 0, the
    map closes with '\\n};' and its last entry carries NO
    trailing comma (verified by recon)."""
    global src
    i = src.find('var %s = {' % name)
    assert i > 0, name + ' start'
    j = src.find('\n};', i)
    assert j > i, name + ' close'
    assert src[j - 1] == '"', name + ' last entry shape: %r' % src[j - 30:j]
    block = src[i:j]
    rows = []
    for k, v in zip(keys, values):
        assert (json.dumps(k, ensure_ascii=False) + ':') not in block, name + ' dup key: ' + k[:60]
        rows.append(js_pair(k, v))
    src = src[:j] + ',\n' + ',\n'.join(rows) + src[j:]

